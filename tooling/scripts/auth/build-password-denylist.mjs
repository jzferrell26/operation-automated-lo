const years = [];
for (let year = 1960; year <= 2030; year += 1) years.push(String(year));

const entries = new Set();

function add(value) {
  const normalized = value.normalize("NFC").toLowerCase();
  if (normalized.length >= 4 && normalized.length <= 64) entries.add(normalized);
}

for (const seed of seeds) {
  add(seed);
  for (const suffix of suffixes) add(seed + suffix);
  for (const year of years) add(seed + year);
  add(seed + seed);
  add(seed + "password");
  add("my" + seed);
  add("the" + seed);
  add(seed + "123456");
  add(seed + "!2345");
}

for (const name of names) {
  for (const year of years) {
    add(name + year);
    add(name + year + "!");
  }
  add(name + name);
  add(name + "password");
  add("password" + name);
}

for (const word of words) {
  for (const other of words) {
    if (word !== other) add(word + other);
  }
  for (const suffix of suffixes) add(word + suffix);
}

const sorted = [...entries].sort();
const longEnough = sorted.filter((entry) => entry.length >= 12).length;

writeFileSync(process.argv[2], `${JSON.stringify(sorted, null, 0)}\n`, "utf8");
console.log("entries:", sorted.length, "of which 12 characters or longer:", longEnough);
